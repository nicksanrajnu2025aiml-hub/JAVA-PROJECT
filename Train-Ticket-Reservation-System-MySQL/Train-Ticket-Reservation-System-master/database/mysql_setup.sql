-- MySQL setup for Train Ticket Reservation System
-- Run in MySQL Workbench or:  mysql -u root -p < database/mysql_setup.sql

CREATE DATABASE IF NOT EXISTS reservation;
USE reservation;

CREATE TABLE IF NOT EXISTS CUSTOMER (
  MAILID VARCHAR(40) PRIMARY KEY,
  PWORD  VARCHAR(20) NOT NULL,
  FNAME  VARCHAR(20) NOT NULL,
  LNAME  VARCHAR(20),
  ADDR   VARCHAR(100),
  PHNO   BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS ADMIN (
  MAILID VARCHAR(40) PRIMARY KEY,
  PWORD  VARCHAR(20) NOT NULL,
  FNAME  VARCHAR(20) NOT NULL,
  LNAME  VARCHAR(20),
  ADDR   VARCHAR(100),
  PHNO   BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS TRAIN (
  TR_NO    BIGINT PRIMARY KEY,
  TR_NAME  VARCHAR(70) NOT NULL,
  FROM_STN VARCHAR(20) NOT NULL,
  TO_STN   VARCHAR(20) NOT NULL,
  SEATS    INT NOT NULL,
  FARE     DECIMAL(8,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS HISTORY (
  TRANSID  VARCHAR(36) PRIMARY KEY,
  MAILID   VARCHAR(40),
  TR_NO    BIGINT,
  `DATE`   DATE,
  FROM_STN VARCHAR(20) NOT NULL,
  TO_STN   VARCHAR(20) NOT NULL,
  SEATS    INT NOT NULL,
  AMOUNT   DECIMAL(10,2) NOT NULL,
  FOREIGN KEY (MAILID) REFERENCES CUSTOMER(MAILID)
);

